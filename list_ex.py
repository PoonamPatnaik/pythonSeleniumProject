# list - Mutable
fruits = ["apple", "banana", "cherry", "date", "elderberry"]
print("{}{}".format("First fruit: ",fruits[0]))
print("{}{}".format("Last fruit: ",fruits[-1]))
print("{}{}".format("Fruits from index 1 to 2:",fruits[1:2]))

# tuple -immutable
person =("Rahul", 25, 5.9)
print("{}{}".format("Age: ",person[1]))